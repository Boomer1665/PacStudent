    static int[,] map;

    public static void Load()
    {
        map = (int[,])template.Clone();
    }

    public static bool InBounds(Vector2Int c)
    {
        return c.x >= MinX && c.x <= MaxX && c.y >= MinY && c.y <= MaxY;
    }

    public static int Get(Vector2Int c)
    {
        return map[MaxY - c.y, c.x - MinX];
    }

    // Can walk on empty space, pellets and power pellets. Everything else is a wall.
    public static bool IsWalkable(Vector2Int c)
    {
        if (!InBounds(c)) return false;
        int v = Get(c);
        return v == 0 || v == 5 || v == 6;
    }

    public static bool HasPellet(Vector2Int c)
    {
        if (!InBounds(c)) return false;
        int v = Get(c);
        return v == 5 || v == 6;
    }

    public static void ClearPellet(Vector2Int c)
    {
        if (HasPellet(c)) map[MaxY - c.y, c.x - MinX] = 0;
    }
